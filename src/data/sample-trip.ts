function act(
  id: string,
  type: ActivityType,
  title: string,
  subs: string[] = [],
  sortOrder = 0,
  extra: Partial<Pick<Activity, 'time' | 'status' | 'notes' | 'extraCost' | 'bookingRef' | 'meetingPoint'>> = {},
) {
  return {
    id,
    type,
    title,
    description: '',
    sortOrder,
    subActivities: subs.map((sub, i) => ({ id: `${id}-s${i}`, title: sub })),
    ...extra,
  }
}

